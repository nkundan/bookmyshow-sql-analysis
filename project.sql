-- 1.List all venues located in Mumbai or Bengaluru, ordered by total_capacity descending.
select * from venues;
select venue_name,venue_type,city,total_capacity from venues where city in ("mumbai","bengaluru") order by total_capacity desc;
-- 2.Count how many events fall under each category (Movies/Plays/Sports/Events/Activities)
select * from events;
select category,count(*) as event_count from events
group by category
order by event_count desc;
-- 3.What is the average baseprice per category?
select e.category,round(avg(s.base_price)) as avg_base_price
from events e join shows s
on e.event_id=s.event_id
group by e.category
order by avg_base_price desc;
-- 4.How many distinct cities does the platform operate in, and how many venues are in each?
select * from venues;
select city,count(distinct(venue_name)) as venue_count
from venues group by city
order by venue_count;
-- 5.Total revenue (Booked status only) by category.
select e.category,round(sum(b.total_amount),2)  as total_revenue 
from shows s join bookings b on s.show_id = b.show_id  join events e
on s.event_id=e.event_id 
where b.booking_status="booked"
group by e.category
order by total_revenue desc;
-- 6.Which venue has hosted the most distinct events?
select v.venue_name,count(distinct(s.venue_id)) as event_count
from shows s join venues v
on v.venue_id=s.venue_id
group by v.venue_name
order by event_count desc;
-- 7.List the top 10 highest-grossing shows
select s.show_id,e.title,v.venue_name,round(sum(b.total_amount),2) as revenue from
bookings b join shows s on b.show_id=s.show_id
join events e on s.event_id=e.event_id
join venues v on s.venue_id=v.venue_id
where b.booking_status="booked"
group by s.show_id
order by revenue desc
limit 10;
-- 8.For each city, total revenue generated by venues located there
select v.city,round(sum(b.total_amount),2) as total_revenue
from venues v join shows s
on v.venue_id=s.venue_id
join bookings b on s.show_id=b.show_id
group by v.city
order by total_revenue desc;
-- 9.List the top 5 movies by number of tickets sold, including their language and genre.
select e.title,e.genre,e.language, sum(b.seats_booked) 
as total_ticket_sold
from events e join shows s
on e.event_id=s.event_id
join bookings b 
on b.show_id=s.show_id
where e.category="Movies" and b.booking_status="Booked"
group by e.title,e.genre,e.language
order by total_ticket_sold desc
limit 5;
-- 10.For each membership tier, how many customers are there and what is their combined total spend?
select c.membership_tier,count(c.customer_id) as total_customer,
round(sum(b.total_amount),2) as total_spend 
from customers c join bookings b
on c.customer_id=b.customer_id
where b.booking_status="Booked"
group by c.membership_tier
order by total_spend desc;
-- 11.Rank venues within each venue_type by total revenue.
SELECT venue_name, venue_type, revenue,
RANK() OVER (PARTITION BY venue_type ORDER BY revenue DESC) AS rnk
FROM (
SELECT v.venue_name, v.venue_type, ROUND(SUM(b.total_amount),2) AS revenue
FROM bookings b
JOIN shows s ON b.show_id = s.show_id
JOIN venues v ON s.venue_id = v.venue_id
WHERE b.booking_status = 'Booked'
GROUP BY v.venue_name, v.venue_type
) t
ORDER BY venue_type, rnk;
-- 12.Compute a running total of daily revenue across the full date range.
SELECT booking_date, daily_revenue,
SUM(daily_revenue) OVER (ORDER BY booking_date) AS running_total
FROM (
SELECT DATE(booking_datetime) AS booking_date, ROUND(SUM(total_amount),2) AS daily_revenue
FROM bookings
WHERE booking_status = 'Booked'
GROUP BY DATE(booking_datetime)
) t
ORDER BY booking_date;
-- 13.Month-over-month revenue growth % (use LAG() over monthly aggregates).
SELECT month, revenue,
ROUND(100.0*(revenue - LAG(revenue) OVER (ORDER BY month))
/ LAG(revenue) OVER (ORDER BY month), 2) AS mom_pct
FROM (
SELECT DATE_FORMAT(booking_datetime, '%Y-%m') AS month, SUM(total_amount) AS revenue
FROM bookings
WHERE booking_status = 'Booked'
GROUP BY month
) t
ORDER BY month;
-- 14.For each customer, find their most recent booking.
SELECT customer_id, booking_id, booking_datetime
FROM (
SELECT customer_id, booking_id, booking_datetime,
ROW_NUMBER() OVER (PARTITION BY customer_id ORDER BY booking_datetime DESC) AS rn
FROM bookings
) t
WHERE rn = 1;
-- 15.Assign customers into 10 spend deciles using NTILE(10) and report average spend per decile.
SELECT decile, ROUND(AVG(spend),2) AS avg_spend
FROM (
SELECT customer_id, SUM(total_amount) AS spend,
NTILE(10) OVER (ORDER BY SUM(total_amount) DESC) AS decile
FROM bookings
WHERE booking_status = 'Booked'
GROUP BY customer_id
) t
GROUP BY decile
ORDER BY decile;
-- 16.Cancellation rate by payment_mode.
SELECT payment_mode,
ROUND(100.0*SUM(CASE WHEN booking_status='Cancelled' THEN 1 ELSE 0 END)/COUNT(*),2) AS
cancel_rate_pct
FROM bookings
GROUP BY payment_mode
ORDER BY cancel_rate_pct DESC;

